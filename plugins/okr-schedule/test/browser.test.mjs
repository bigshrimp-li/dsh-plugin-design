async function executable() {
  const choices = [process.env.CHROME_PATH, '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'];
  for (const candidate of choices.filter(Boolean)) { try { await fs.access(candidate); return candidate; } catch { /* try the next installed browser */ } }
  throw new Error('A local Chrome/Chromium is required; set CHROME_PATH');
}

